export function classifyGame(slug: string, year: number): GameMeta {
  let demandTier: DemandTier = "moderate";

  if (EXTREME_SLUGS.has(slug)) demandTier = "extreme";
  else if (DEMANDING_SLUGS.has(slug)) demandTier = "demanding";
  else if (LIGHT_SLUGS.has(slug)) demandTier = "light";
  else if (year >= 2023) demandTier = "demanding";
  else if (year <= 2016) demandTier = "moderate";

  const supportsRayTracing = RT_SLUGS.has(slug) || (year >= 2022 && demandTier !== "light");

  return {
    demandTier,
    supportsRayTracing,
    upscalingSupport: resolveUpscalingSupport(slug, year),
    steamAppId: STEAM_APP_IDS[slug],
  };
}
